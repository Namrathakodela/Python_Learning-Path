# String Formatting

name = "Namratha"
age = 21
branch = "CSE"

# Using f-string
print(f"My name is {name}.")
print(f"I am {age} years old.")
print(f"I am studying {branch}.")

# Expressions inside f-string
a = 10
b = 20

print(f"Sum of {a} and {b} is {a + b}")

# Formatting decimal values
price = 99.5678

print(f"Price: {price:.2f}")